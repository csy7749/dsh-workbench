import assert from 'node:assert/strict'
import { existsSync, linkSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, symlinkSync, unlinkSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { createNativeGameStudio } from '../src/host/native-game-studio.mjs'

const root = mkdtempSync(join(tmpdir(), 'native-game-studio-'))
const workspace = join(root, 'workspace')
const linkedWorkspace = join(root, 'linked-workspace')
const outside = join(root, 'outside')
const studio = createNativeGameStudio()
const create = options => studio.create({ workspaceRoot: workspace, productId: 'test-product', ...options })
const build = (slug = 'star-catcher', options = {}) => studio.build({ workspaceRoot: workspace, productId: 'test-product', slug, ...options })
try {
  mkdirSync(workspace)
  mkdirSync(linkedWorkspace)
  mkdirSync(outside)
  const created = create({ slug: 'star-catcher', title: '星光采集' })
  assert.equal(created.project, 'games/star-catcher')
  assert.equal(created.template, 'canvas-collector')
  assert.equal(created.bytes, Buffer.byteLength(readFileSync(join(workspace, created.project, 'dist/index.html'))))
  assert.match(created.buildId, /^[a-f0-9]{12}$/)
  const originalHtml = readFileSync(join(workspace, created.artifact), 'utf8')
  assert.match(originalHtml, /connect-src 'none'/)
  assert.equal(created.hash, createHash('sha256').update(originalHtml).digest('hex'))
  assert.equal(created.previewAvailable, false)
  assert.equal(created.playtestStatus, 'not_assessed')
  const firstBuild = build()
  assert.equal(firstBuild.buildId, created.buildId)
  assert.equal(firstBuild.bytes, created.bytes)
  assert.equal(firstBuild.reused, true)
  const target = { workspaceRoot: workspace, productId: 'test-product', slug: created.slug, buildId: created.buildId }
  const snapshot = studio.readBuild(target)
  assert.equal(snapshot.html, originalHtml)
  assert.equal(snapshot.buildCurrent, true)
  assert.throws(() => studio.readBuild({ ...target, buildId: '../outside' }), /game_build_id_invalid/)
  const exported = studio.exportBuild(target)
  assert.equal(readFileSync(join(workspace, exported.exportPath), 'utf8'), originalHtml)
  assert.equal(exported.hash, created.hash)
  assert.equal(studio.exportBuild(target).reused, true)
  writeFileSync(join(workspace, exported.exportPath), 'conflicting export')
  assert.throws(() => studio.exportBuild(target), /game_export_conflict/)
  assert.equal(readFileSync(join(workspace, exported.exportPath), 'utf8'), 'conflicting export')
  const png = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])
  const report = studio.recordPlaytest({ ...target, report: { summary: 'Errors: none; Screenshots: end.png', finalPhase: 'won', errors: 0, requests: 0, playtestStatus: 'passed' }, screenshots: [{ name: 'end.png', data: png }] })
  assert.equal(studio.readPlaytest({ ...target, ...report }).buildId, created.buildId)
  assert.match(report.summary, /Screenshots: games\//)
  assert.throws(() => studio.readPlaytest({ ...target, reportPath: '../report.json', reportHash: report.reportHash }), /game_playtest_identity_invalid/)
  assert.throws(() => studio.recordPlaytest({ ...target, report: {}, screenshots: [{ name: '../bad.png', data: png }] }), /game_playtest_screenshot_invalid/)
  writeFileSync(join(workspace, report.screenshots[0]), Buffer.from('corrupt png'))
  assert.throws(() => studio.readPlaytest({ ...target, reportPath: report.reportPath, reportHash: report.reportHash }), /game_playtest_integrity_invalid/)
  writeFileSync(join(workspace, report.screenshots[0]), png)
  writeFileSync(join(workspace, report.reportPath), '{}')
  assert.throws(() => studio.readPlaytest({ ...target, reportPath: report.reportPath, reportHash: report.reportHash }), /game_playtest_integrity_invalid/)
  const other = create({ slug: 'other-game', title: '第二个工程' })
  assert.notEqual(other.projectId, created.projectId)
  assert.throws(() => build('star-catcher', { productId: 'different-product' }), /game_product_mismatch/)
  const sourcePath = join(workspace, created.project, 'game.js')
  writeFileSync(sourcePath, readFileSync(sourcePath, 'utf8') + '\n// revision 2\n')
  const secondBuild = build()
  assert.notEqual(secondBuild.buildId, created.buildId)
  assert.equal(readFileSync(join(workspace, created.artifact), 'utf8'), originalHtml, 'old snapshot is unchanged')
  const latestHtml = readFileSync(join(workspace, secondBuild.artifact), 'utf8')
  assert.equal(readFileSync(join(workspace, created.project, 'dist/index.html'), 'utf8'), latestHtml)
  const validSource = readFileSync(sourcePath, 'utf8')
  writeFileSync(sourcePath, '(() => {')
  assert.equal(studio.readBuild(target).buildCurrent, false, 'history survives malformed workcopy')
  assert.throws(() => build(), /game_source_syntax_invalid/)
  assert.equal(readFileSync(join(workspace, created.project, 'dist/index.html'), 'utf8'), latestHtml, 'syntax failure preserves last good build')
  assert.equal(existsSync(join(workspace, created.project, '.studio/build.lock')), false)
  writeFileSync(sourcePath, 'throw new Error("host must not execute source")')
  assert.doesNotThrow(() => build())
  writeFileSync(sourcePath, 'const x = "</script><script>alert(1)</script>"')
  assert.throws(() => build(), /game_source_html_delimiter/)
  writeFileSync(sourcePath, validSource)
  assert.throws(() => create({ slug: '../outside', title: '越界' }), /game_slug_invalid/)
  assert.throws(() => create({ slug: 'con', title: '保留名称' }), /game_slug_invalid/)
  assert.throws(() => create({ slug: 'bad-rules', title: '规则错误', rules: { durationSeconds: 0, hearts: 3 } }), /game_rules_invalid/)
  assert.equal(existsSync(join(workspace, 'games/bad-rules')), false)
  assert.throws(() => create({ slug: 'voxel', title: '未接入', template: 'voxel' }), /game_template_unavailable/)
  assert.throws(() => create({ slug: 'star-catcher', title: '重复' }), /game_project_exists/)
  assert.throws(() => build('missing'), /ENOENT/)
  symlinkSync(outside, join(linkedWorkspace, 'games'), 'junction')
  assert.throws(() => create({ workspaceRoot: linkedWorkspace, slug: 'escape', title: '越界' }), /game_directory_unsafe/)
  symlinkSync(outside, join(workspace, 'games/escape'), 'junction')
  assert.throws(() => build('escape'), /game_directory_unsafe/)
  assert.equal(readdirSync(outside).length, 0, 'symlinks never write to outside directory')
  const lockPath = join(workspace, created.project, '.studio/build.lock')
  writeFileSync(lockPath, 'existing owner', { flag: 'wx' })
  assert.throws(() => build(), /game_build_busy/)
  assert.equal(readFileSync(lockPath, 'utf8'), 'existing owner')
  unlinkSync(lockPath)
  const hardLink = join(outside, 'linked-source.js')
  linkSync(sourcePath, hardLink)
  assert.throws(() => build(), /game_file_unsafe/)
  unlinkSync(hardLink)
  assert.equal(build().buildId, secondBuild.buildId, 'service recovers after bad source and lock removal')
  writeFileSync(join(workspace, secondBuild.artifact), 'damaged snapshot')
  assert.throws(() => studio.readBuild({ ...target, buildId: secondBuild.buildId }), /game_build_integrity_invalid/)
  assert.throws(() => build(), /game_build_snapshot_conflict/)
  assert.equal(readFileSync(join(workspace, secondBuild.artifact), 'utf8'), 'damaged snapshot', 'never repairs history by overwriting it')
  const manifestPath = join(workspace, 'games/star-catcher/game.json')
  writeFileSync(manifestPath, JSON.stringify({ schemaVersion: 1, projectId: 'x', title: '', templateId: 'other', templateVersion: 1 }))
  assert.throws(() => build(), /game_manifest_invalid/)
  assert.equal(readdirSync(join(workspace, 'games')).some(name => name.startsWith('.create-')), false)
  console.log('PASS native game studio: product isolation, real hash/bytes, source snapshots, cache validation, failed-build preservation, parse-only build, unsafe paths/files, busy lock and recovery')
} finally {
  rmSync(root, { recursive: true, force: true })
}
